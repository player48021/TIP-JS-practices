import assert from "node:assert/strict";
import { initialTasks } from "../src/data.js";
import { addTask, updateTask, toggleTask, deleteTask, validateTaskDraft } from "../src/task-service.js";
import { loadTasks, saveTasks, removeSavedTasks } from "../src/task-storage.js";
let result = addTask(initialTasks, { id: 20, title: "Тест", priority: "low" });
assert.equal(result.ok, true);
assert.equal(addTask(initialTasks, { id: 1, title: "Дубликат", priority: "low" }).ok, false);
assert.equal(validateTaskDraft({ id: 20, title: "   ", priority: "high" }, initialTasks).ok, false);
result = updateTask(initialTasks, 4, "Новое название", "low");
assert.equal(result.ok, true);
assert.equal(result.tasks.find(t => t.id === 4).title, "Новое название");
assert.equal(initialTasks.find(t => t.id === 4).title, "Подготовить модель задач");
assert.equal(toggleTask(initialTasks, 4).tasks.find(t => t.id === 4).completed, true);
assert.equal(deleteTask(initialTasks, 4).tasks.some(t => t.id === 4), false);
const map = new Map();
const storage = { getItem: k => map.has(k) ? map.get(k) : null, setItem: (k,v) => map.set(k,v), removeItem: k => map.delete(k) };
assert.equal(saveTasks(storage, "x", initialTasks).ok, true);
assert.equal(loadTasks(storage, "x", []).tasks.length, initialTasks.length);
assert.equal(removeSavedTasks(storage, "x").ok, true);
console.log("ПР4: все проверки пройдены.");
